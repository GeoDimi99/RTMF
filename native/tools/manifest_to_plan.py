#!/usr/bin/env python3
"""
manifest_to_plan.py

Converts a test manifest (the same format used by the other implementations,
e.g. tests/test_0_code/manifest.yaml) into the C header that the native
Execution Manager compiles in (schedule_plan.h). The native implementation has
no runtime manifest parsing: the schedule is still compiled in, it is just
generated from the manifest instead of being written by hand in main.c.

Usage:
    python3 manifest_to_plan.py <manifest.yaml> <output schedule_plan.h>

Mapping (same semantics as the other implementations):
    schedule.iterations          -> PLAN_ITERATIONS (default 1)
    schedule.name                -> PLAN_SCHEDULE_NAME
    task.id                      -> task id
    task.image                   -> task name (stress_task_N)
    task.policy                  -> other|normal, batch, idle, fifo, rr
    task.priority                -> RT priority (fifo/rr) or nice value (other/batch)
    task.cpu_affinity            -> CPU core of the task thread
    task.start / task.deadline   -> activation / expiration time (ms)
    task.inputs.total_ops        -> input_t.total_ops      (default 100)
    task.inputs.io_percentage    -> input_t.io_percentage  (default 0)
"""

import sys

import yaml

POLICIES = {
    "other": "SCHED_OTHER",
    "normal": "SCHED_OTHER",  # SCHED_NORMAL is the kernel-side alias of SCHED_OTHER
    "batch": "SCHED_BATCH",
    "idle": "SCHED_IDLE",
    "fifo": "SCHED_FIFO",
    "rr": "SCHED_RR",
}


def fail(msg):
    sys.exit(f"[ERROR] manifest_to_plan: {msg}")


def input_value(task, key, default):
    entry = (task.get("inputs") or {}).get(key)
    if entry is None:
        return default
    value = entry.get("value", default) if isinstance(entry, dict) else entry
    return int(value)


def c_string(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) != 3:
        fail("usage: manifest_to_plan.py <manifest.yaml> <schedule_plan.h>")
    manifest_path, out_path = sys.argv[1], sys.argv[2]

    with open(manifest_path) as f:
        manifest = yaml.safe_load(f) or {}

    schedule = manifest.get("schedule") or {}
    tasks = schedule.get("tasks") or []
    if not tasks:
        fail(f"no schedule.tasks in {manifest_path}")

    iterations = int(schedule.get("iterations", 1))
    if iterations <= 0:
        fail(f"invalid schedule.iterations {iterations}")

    lines = []
    seen_ids = set()
    for t in tasks:
        tid = int(t["id"])
        if tid in seen_ids:
            fail(f"duplicated task id {tid}")
        seen_ids.add(tid)

        policy_name = str(t.get("policy", "other")).lower()
        if policy_name not in POLICIES:
            fail(f"task {tid}: unsupported policy '{policy_name}' (supported: {', '.join(POLICIES)})")
        policy = POLICIES[policy_name]

        priority = int(t.get("priority", 0))
        if not -128 <= priority <= 127:
            fail(f"task {tid}: priority {priority} out of range")
        start, deadline = int(t["start"]), int(t["deadline"])
        if not 0 <= start < deadline:
            fail(f"task {tid}: start ({start}) must be >= 0 and < deadline ({deadline})")

        lines.append(
            f"    in = g_new0(input_t, 1);\n"
            f"    in->total_ops = {input_value(t, 'total_ops', 100)};\n"
            f"    in->io_percentage = {input_value(t, 'io_percentage', 0)};\n"
            f"    schedule_add_task(sched, {tid}, {c_string(t['image'])}, task_main, {policy}, {priority}, "
            f"{int(t['cpu_affinity'])}, 1, NULL, {start}, {deadline}, in);\n"
        )

    header = f"""/* Generated by tools/manifest_to_plan.py from {manifest_path}
 * Do not edit: change the manifest and rebuild (start-test.sh regenerates it). */
#ifndef SCHEDULE_PLAN_H
#define SCHEDULE_PLAN_H

#include "schedule.h"
#include "app_task.h"

#define PLAN_SCHEDULE_NAME {c_string(schedule.get("name", "schedule"))}
#define PLAN_ITERATIONS {iterations}

/* Add the tasks of the manifest to the schedule (the inputs are freed by the schedule) */
static inline void schedule_plan_add_tasks(schedule_t *sched) {{
    input_t *in;

{chr(10).join(lines)}}}

#endif // SCHEDULE_PLAN_H
"""
    with open(out_path, "w") as f:
        f.write(header)
    print(f"[INFO] schedule plan: {len(tasks)} tasks, {iterations} iterations -> {out_path}")


if __name__ == "__main__":
    main()
